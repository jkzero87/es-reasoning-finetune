#!/usr/bin/env python3
"""Write results/label_audit_2026-11-12.md: the 2026-11-12 labels of the
scripts/label_sample.py sample (seed 20261112) and the es/en tally per label.

Labels (one annotator, Claude; questions/options only, passages not reviewed):
E = translation error in the Spanish item, A = ambiguous, O = correct Spanish.
The id lists are recomputed with label_sample.py's own selection on the same raw
files, so a label for an id outside its group stops the script.

Tally per sample group x label: n, es/en ratio of summed reasoning_content
characters, and share of excess = sum(es - en) of the label's ids over sum(es - en)
of the 20 ids of the group, and over all paired ids of the raw file.
Usage: scripts/label_audit.py  (no arguments; run from the repo root)
"""
import json
import random
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "label_audit_2026-11-12.md"
SOURCES = {
    "mgsm27b": Path.home() / "es-eval" / "results" / "mgsm_raw.jsonl",
    "belebele9b": ROOT / "results" / "belebele_raw.base9b.jsonl",
}
LABELS = {
    ("mgsm27b", "worst-20"): {"E": [215, 39, 71, 199, 111, 94], "A": [120, 235, 182, 250]},
    ("mgsm27b", "random-20"): {"A": [148]},
    ("belebele9b", "worst-20"): {"E": [376, 388, 224, 483, 304], "A": [451, 166, 55]},
    ("belebele9b", "random-20"): {"A": [386]},
}


def sample(raw):
    """Same selection as scripts/label_sample.py."""
    rows = {}
    for line in raw.open(encoding="utf-8"):
        r = json.loads(line)
        rows[(r["id"], r["lang"])] = r
    ids = sorted({i for i, l in rows if l == "es"} & {i for i, l in rows if l == "en"})
    L = lambda i, g: len(rows[(i, g)].get("reasoning_content") or "")
    worst = sorted(ids, key=lambda i: L(i, "es") - L(i, "en"), reverse=True)[:20]
    rest = [i for i in ids if i not in worst]
    random.seed(20261112)
    rand = random.sample(rest, 20)
    return ids, worst, rand, L


def main():
    out = ["# Label audit 2026-11-12", "",
           "Generated by `scripts/label_audit.py`; do not edit by hand.", "",
           "One annotator (Claude); questions and options only, passages not reviewed. "
           "E = translation error in the Spanish item, A = ambiguous, O = correct Spanish. "
           "Sample: `scripts/label_sample.py`, seed 20261112, worst-20 by es−en reasoning characters "
           "and 20 random ids from the rest (`results/label_sample.md`).", ""]
    tally = ["## es/en tally", "",
             "Ratio = Σ es reasoning chars / Σ en reasoning chars over the label's ids. "
             "Share = Σ(es−en) of the label's ids over Σ(es−en) of the group's 20 ids, and over all paired ids of the raw file.", "",
             "| source | group | label | n | Σ es chars | Σ en chars | es/en | share of group excess | share of benchmark excess |",
             "|---|---|---|---:|---:|---:|---:|---:|---:|"]
    for src, raw in SOURCES.items():
        ids, worst, rand, L = sample(raw)
        total_excess = sum(L(i, "es") - L(i, "en") for i in ids)
        out += [f"## {src}", "", f"Raw: `{raw.relative_to(Path.home()) if raw.is_relative_to(Path.home()) else raw}`, {len(ids)} paired ids, Σ(es−en) = {total_excess} chars.", ""]
        for grp, sel in (("worst-20", worst), ("random-20", rand)):
            lab = {i: "O" for i in sel}
            for k, v in LABELS[(src, grp)].items():
                for i in v:
                    if i not in lab:
                        sys.exit(f"STOP: {src} {grp}: labelled id {i} is not in the sample")
                    lab[i] = k
            out += [f"### {grp}", "", "| id | label | es chars | en chars |", "|---:|---|---:|---:|"]
            out += [f"| {i} | {lab[i]} | {L(i, 'es')} | {L(i, 'en')} |" for i in sel]
            out.append("")
            grp_excess = sum(L(i, "es") - L(i, "en") for i in sel)
            for k in ("E", "A", "O", "all"):
                ks = sel if k == "all" else [i for i in sel if lab[i] == k]
                if not ks:
                    continue
                es, en = sum(L(i, "es") for i in ks), sum(L(i, "en") for i in ks)
                ex = sum(L(i, "es") - L(i, "en") for i in ks)
                tally.append(f"| {src} | {grp} | {k} | {len(ks)} | {es} | {en} | {es / en:.3f} | "
                             f"{ex / grp_excess:.3f} | {ex / total_excess:.3f} |")
    OUT.write_text("\n".join(out + tally) + "\n", encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
